# Build all 16-bit columns for MESSAGE
COLUMNS = []
for ch in MESSAGE.upper():
    for col8 in FONT_8.get(ch, FONT_8[" "]):
        # Stretch 8 pixels to 16 pixels tall
        col16 = "".join(bit * 2 for bit in col8)
        COLUMNS.append(col16)

if not COLUMNS:
    COLUMNS = ["0" * 16]

step = 0


@app.route("/endpoint", methods=["GET", "POST"])
def scroll_16():
    global step
    data = request.get_json(silent=True) or {}

    # Turn your input switch ON ("1") and trigger POST to restart message
    if str(data.get("value")) == "1":
        step = 0

    slice_16 = COLUMNS[step]
    step = (step + 1) % len(COLUMNS)
    return slice_16
